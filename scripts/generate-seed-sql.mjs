// Turns src/lib/seed.js (the fictional demo community) into supabase/seed.sql.
// Usage: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEMO_PROFILES, DEMO_ACTIVITIES, DEMO_ANNOUNCEMENTS } from '../src/lib/seed.js';

const q = (s) => (s === null || s === undefined || s === '' ? "''" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const TZ = 'America/Vancouver';

// Next <weekday> at <time> in Vancouver, computed when the seed runs.
const nextAt = (weekday, time) => `((date_trunc('day', now() at time zone '${TZ}')
      + (((${weekday} - extract(dow from now() at time zone '${TZ}')::int) + 7) % 7) * interval '1 day'
      + time '${time}') at time zone '${TZ}')`;

const out = [];
out.push(`-- GENERATED by scripts/generate-seed-sql.mjs from src/lib/seed.js. Do not edit by hand.
-- FICTIONAL demo community for Kitside. Every person, activity and post below is made up.
-- Places mentioned are examples only and are not affiliated with or endorsed by Kitside.
-- Run after supabase/migrations/*_kitside_init.sql.
-- NON-DESTRUCTIVE: only inserts rows that aren't there yet (on conflict do nothing).
-- It never deletes or changes existing rows, so it's safe to run more than once.
-- To hide all example content later, set VITE_SHOW_DEMO=false (no database change needed).

begin;
`);

out.push('insert into public.profiles (id, name, role, title, bio, neighbourhood, interests, looking_for, working_on, is_remote, avatar_hue, is_demo) values');
out.push(DEMO_PROFILES.map((p) =>
  `  (${q(p.id)}, ${q(p.name)}, ${q(p.role)}, ${q(p.title)}, ${q(p.bio)}, ${q(p.neighbourhood)}, ${arr(p.interests)}, ${arr(p.lookingFor)}, ${q(p.workingOn)}, ${p.isRemote}, ${p.avatarHue}, true)`
).join(',\n') + '\non conflict (id) do nothing;\n');

out.push('insert into public.activities (id, host_id, title, description, category, location, starts_at, is_demo) values');
out.push(DEMO_ACTIVITIES.map((a) =>
  `  (${q(a.id)}, ${q(a.hostId)}, ${q(a.title)}, ${q(a.description)}, ${q(a.category)}, ${q(a.location)}, ${nextAt(a.weekday, a.time)}, true)`
).join(',\n') + '\non conflict (id) do nothing;\n');

out.push('insert into public.announcements (id, author_id, title, details, category, location, happens_at, is_demo, created_at) values');
out.push(DEMO_ANNOUNCEMENTS.map((a) =>
  `  (${q(a.id)}, ${q(a.authorId)}, ${q(a.title)}, ${q(a.details)}, ${q(a.category)}, ${q(a.location || '')}, ${a.time ? `time '${a.time}'` : 'null'}, true, now() - interval '${a.hoursAgo} hours')`
).join(',\n') + '\non conflict (id) do nothing;\n');

out.push('insert into public.activity_interests (activity_id, profile_id) values');
out.push(DEMO_ACTIVITIES.flatMap((a) => a.interested.map((p) => `  (${q(a.id)}, ${q(p)})`)).join(',\n') + '\non conflict do nothing;\n');

out.push('insert into public.announcement_interests (announcement_id, profile_id) values');
out.push(DEMO_ANNOUNCEMENTS.flatMap((a) => a.interested.map((p) => `  (${q(a.id)}, ${q(p)})`)).join(',\n') + '\non conflict do nothing;\n');
out.push('commit;\n');

const target = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target}`);
